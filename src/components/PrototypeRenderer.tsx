import { useEffect, useRef, useState } from 'react'
import { buildPrototypeHTML } from '@/lib/buildPrototypeHTML'
import type { ProblemAnalysis } from '@/types'

interface PrototypeRendererProps {
  jsxCode: string
  analysis: ProblemAnalysis
  onBack: () => void
  onRegenerate: () => void
}

export default function PrototypeRenderer({
  jsxCode,
  analysis,
  onBack,
  onRegenerate,
}: PrototypeRendererProps) {
  const iframeRef = useRef<HTMLIFrameElement>(null)
  const blobUrlRef = useRef<string | null>(null)
  const [iframeLoading, setIframeLoading] = useState(true)

  useEffect(() => {
    // Revoke previous blob URL
    if (blobUrlRef.current) {
      URL.revokeObjectURL(blobUrlRef.current)
    }

    const html = buildPrototypeHTML(jsxCode)
    const blob = new Blob([html], { type: 'text/html' })
    const url = URL.createObjectURL(blob)
    blobUrlRef.current = url

    setIframeLoading(true)
    if (iframeRef.current) {
      iframeRef.current.src = url
    }

    return () => {
      if (blobUrlRef.current) {
        URL.revokeObjectURL(blobUrlRef.current)
        blobUrlRef.current = null
      }
    }
  }, [jsxCode])

  return (
    <div className="flex flex-col min-h-screen pt-14 pb-6 px-4">
      {/* Top controls */}
      <div className="max-w-5xl mx-auto w-full mt-6 mb-4 flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4">
        <div>
          <button
            onClick={onBack}
            className="text-terminal-green/50 hover:text-terminal-green font-mono text-xs tracking-widest uppercase flex items-center gap-2 transition-colors"
          >
            ← BACK TO ANALYSIS
          </button>
          <div className="mt-1 text-terminal-green/30 text-xs font-mono max-w-md truncate">
            // {analysis.rawProblem}
          </div>
        </div>

        <button
          onClick={onRegenerate}
          className="btn-terminal-amber text-xs px-5 py-2 tracking-widest"
        >
          ↺ REGENERATE
        </button>
      </div>

      {/* Browser chrome wrapper */}
      <div className="max-w-5xl mx-auto w-full flex-1 flex flex-col">
        {/* Browser top bar */}
        <div className="border border-terminal-green/20 border-b-0 bg-terminal-surface flex items-center gap-3 px-4 py-2.5">
          {/* Traffic lights */}
          <div className="flex gap-1.5">
            <div className="w-3 h-3 rounded-full bg-red-500/70" />
            <div className="w-3 h-3 rounded-full bg-yellow-500/70" />
            <div className="w-3 h-3 rounded-full bg-green-500/70" />
          </div>
          {/* Address bar */}
          <div className="flex-1 bg-terminal-dark/60 border border-terminal-green/15 px-3 py-1 text-terminal-green/40 text-xs font-mono rounded-sm">
            prototype://ai-generated/{analysis.rawProblem.slice(0, 30).replace(/\s+/g, '-').toLowerCase()}...
          </div>
          {/* Label */}
          <span className="text-terminal-amber/60 text-xs font-mono hidden sm:block tracking-wider">
            AI PROTOTYPE
          </span>
        </div>

        {/* Iframe */}
        <div className="flex-1 border border-terminal-green/20 relative bg-white" style={{ minHeight: '600px' }}>
          {iframeLoading && (
            <div className="absolute inset-0 bg-terminal-dark flex items-center justify-center z-10">
              <div className="flex flex-col items-center gap-4 text-terminal-green">
                <div className="flex gap-1">
                  {[0, 1, 2, 3].map((i) => (
                    <div
                      key={i}
                      className="w-2 h-2 bg-terminal-green rounded-full animate-bounce"
                      style={{ animationDelay: `${i * 0.15}s` }}
                    />
                  ))}
                </div>
                <span className="text-xs font-mono tracking-widest uppercase text-terminal-green/60">
                  Initializing prototype...
                </span>
              </div>
            </div>
          )}
          <iframe
            ref={iframeRef}
            sandbox="allow-scripts"
            title="AI Generated Prototype"
            onLoad={() => setIframeLoading(false)}
            className="w-full h-full border-0"
            style={{ minHeight: '600px' }}
          />
        </div>

        {/* Footer bar */}
        <div className="border border-terminal-green/20 border-t-0 bg-terminal-surface px-4 py-2 flex items-center justify-between">
          <span className="text-terminal-green/30 text-xs font-mono">
            Generated by GPT-4o · Rendered in isolated sandbox
          </span>
          <div className="flex items-center gap-2">
            <span className="w-1.5 h-1.5 rounded-full bg-terminal-green animate-pulse" />
            <span className="text-terminal-green/40 text-xs font-mono">LIVE</span>
          </div>
        </div>
      </div>
    </div>
  )
}
